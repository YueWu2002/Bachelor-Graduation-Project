% auxiliary functions

function [y] = Dup3(x)
y = x;
end

function [y] = Perm3(x)
y = [x; x; x];
end

function [y] = Dup21(x)
y = [x; x; x];
end

function [y] = Perm21(x)
y = [
    1.0 - 2*x; x; x; 
    x; 1.0 - 2*x; x; 
    x; x; 1.0 - 2*x
];
end

function [y] = Dup111(x)
y = [x; x; x; x; x; x];
end

function [y] = Perm111(a,b)
y = [
    a;      b;      1-a-b; 
    a;      1-a-b;  b; 
    b;      a;      1-a-b; 
    b;      1-a-b;  a; 
    1-a-b;  a;      b; 
    1-a-b;  b;      a
];
end